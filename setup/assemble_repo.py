#!/usr/bin/env python3
"""Copies the clean, publishable Speed Force sources from the development tree into
speedforce/ (the GitHub repository). Nothing from the game is copied: no recompiled code,
no analysis output, no game files, no logs."""
import os, shutil, sys

G = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')      # F:\Justice League Heroes.xiso
R = os.path.join(G, 'speedforce')
XR = os.path.join(G, 'xboxrecomp')

SKIP_DIRS = {'.git', '__pycache__', 'build', 'build-mingw', 'game_files', 'output', 'obj', '.vs'}
SKIP_EXT = ('.orig', '.pyc', '.log', '.obj', '.exe', '.pdb', '.ilk')


def keep_file(n):
    low = n.lower()
    return not (low.endswith(SKIP_EXT) or '.pre_' in low or low.startswith('xbox_kernel'))


def copytree(src, dst):
    for dp, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        rel = os.path.relpath(dp, src)
        out = os.path.join(dst, rel)
        os.makedirs(out, exist_ok=True)
        for f in files:
            if keep_file(f):
                shutil.copy2(os.path.join(dp, f), os.path.join(out, f))


def main():
    for d in ('toolkit', 'game', 'jlh-upscale', 'assets'):
        shutil.rmtree(os.path.join(R, d), ignore_errors=True)
    copytree(os.path.join(XR, 'xboxrecomp-blinx2-portability'), os.path.join(R, 'toolkit'))
    # game project: hand-written port code only; src/recomp/gen is regenerated by the setup
    g = os.path.join(R, 'game')
    os.makedirs(os.path.join(g, 'src'))
    shutil.copy2(os.path.join(XR, 'jlh-recomp', 'CMakeLists.txt'), g)
    for f in ('main.c', 'recomp_manual.c', 'speedforce.rc', 'speedforce.ico'):
        shutil.copy2(os.path.join(XR, 'jlh-recomp', 'src', f), os.path.join(g, 'src', f))
    os.makedirs(os.path.join(g, 'seeds'))
    for f in ('jlh_seeds.json', 'add_cave.py', 'recomp_with_cave.py'):
        shutil.copy2(os.path.join(G, 'runner', 'jobs', f), os.path.join(g, 'seeds', f))
    up = os.path.join(R, 'jlh-upscale')
    os.makedirs(up)
    for f in ('jlh_upscale.cpp', 'jlh_upscale.h'):
        shutil.copy2(os.path.join(XR, 'jlh-upscale', f), up)
    a = os.path.join(R, 'assets')
    os.makedirs(a)
    shutil.copy2(os.path.join(XR, 'jlh-recomp', 'build-mingw', 'jlh_icons.pack'), a)
    hp = os.path.join(G, 'JLH_project_handoff', 'jlh-handoff', 'project')
    d = os.path.join(R, 'docs', 'mod')
    os.makedirs(d, exist_ok=True)
    for f in ('FINDINGS.md', 'NOTES_any_character_mod.md'):
        if os.path.exists(os.path.join(hp, f)):
            shutil.copy2(os.path.join(hp, f), d)
    print('repository sources assembled in', R)


if __name__ == '__main__':
    main()
